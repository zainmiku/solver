-- ------------------------------------------------------------
-- PostgreSQL 版本数据库脚本
-- 说明：请先创建数据库，再执行当前脚本。
-- 例如：CREATE DATABASE solver_platform;
-- ------------------------------------------------------------

-- ------------------------------------------------------------
-- 0. 枚举类型
-- ------------------------------------------------------------
CREATE TYPE user_role AS ENUM ('ADMIN', 'OPERATOR', 'VIEWER');
CREATE TYPE server_status AS ENUM ('ONLINE', 'OFFLINE', 'MAINTENANCE', 'ERROR');
CREATE TYPE gpu_status AS ENUM ('AVAILABLE', 'BUSY', 'RESERVED', 'ERROR', 'MAINTENANCE');
CREATE TYPE solver_priority AS ENUM ('LOW', 'NORMAL', 'HIGH', 'URGENT');
CREATE TYPE task_status AS ENUM (
  'PENDING',
  'QUEUED',
  'RUNNING',
  'PAUSED',
  'COMPLETED',
  'FAILED',
  'CANCELLED',
  'TIMEOUT'
);
CREATE TYPE queue_status AS ENUM ('QUEUED', 'PROCESSING', 'REMOVED');
CREATE TYPE log_level AS ENUM ('DEBUG', 'INFO', 'WARN', 'ERROR', 'CRITICAL');
CREATE TYPE config_type AS ENUM ('STRING', 'INTEGER', 'BOOLEAN', 'JSON', 'FLOAT');

-- ------------------------------------------------------------
-- 1. 用户与权限表
-- ------------------------------------------------------------
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  email VARCHAR(100) DEFAULT NULL,
  full_name VARCHAR(100) DEFAULT NULL,
  role user_role NOT NULL DEFAULT 'VIEWER',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMP DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT uk_username UNIQUE (username),
  CONSTRAINT uk_email UNIQUE (email)
);

CREATE INDEX idx_role ON users (role);
CREATE INDEX idx_created_at ON users (created_at);

-- ------------------------------------------------------------
-- 2. 计算服务器表
-- ------------------------------------------------------------
CREATE TABLE compute_servers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  host VARCHAR(100) NOT NULL,
  port INTEGER NOT NULL DEFAULT 22,
  ssh_username VARCHAR(50) NOT NULL,
  ssh_password VARCHAR(255) DEFAULT NULL,
  ssh_private_key_path VARCHAR(500) DEFAULT NULL,
  description TEXT DEFAULT NULL,
  status server_status NOT NULL DEFAULT 'ONLINE',
  gpu_count INTEGER NOT NULL DEFAULT 0,
  max_concurrent_tasks INTEGER NOT NULL DEFAULT 4,
  tags JSONB DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  last_heartbeat TIMESTAMP DEFAULT NULL,
  CONSTRAINT uk_host_port UNIQUE (host, port),
  CONSTRAINT uk_name UNIQUE (name)
);

CREATE INDEX idx_status ON compute_servers (status);
CREATE INDEX idx_gpu_count ON compute_servers (gpu_count);

-- ------------------------------------------------------------
-- 3. GPU资源表
-- ------------------------------------------------------------
CREATE TABLE gpu_resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id BIGINT NOT NULL,
  gpu_index INTEGER NOT NULL,
  name VARCHAR(100) DEFAULT NULL,
  memory_mb INTEGER DEFAULT NULL,
  status gpu_status NOT NULL DEFAULT 'AVAILABLE',
  current_task_id BIGINT DEFAULT NULL,
  utilization DECIMAL(5,2) DEFAULT 0.00,
  temperature DECIMAL(5,2) DEFAULT NULL,
  last_checked TIMESTAMP DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT uk_server_gpu UNIQUE (server_id, gpu_index),
  CONSTRAINT fk_gpu_server FOREIGN KEY (server_id)
    REFERENCES compute_servers (id) ON DELETE CASCADE
);

CREATE INDEX idx_status ON gpu_resources (status);
CREATE INDEX idx_current_task ON gpu_resources (current_task_id);
CREATE INDEX idx_gpu_server_status ON gpu_resources (server_id, status, gpu_index);
CREATE INDEX idx_gpu_utilization ON gpu_resources (utilization);

-- ------------------------------------------------------------
-- 4. 求解器版本表
-- ------------------------------------------------------------
CREATE TABLE solver_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  version VARCHAR(50) NOT NULL,
  full_version VARCHAR(200) NOT NULL,
  file_path VARCHAR(500) NOT NULL,
  description TEXT DEFAULT NULL,
  uploaded_by BIGINT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  total_runs INTEGER NOT NULL DEFAULT 0,
  success_count INTEGER NOT NULL DEFAULT 0,
  failure_count INTEGER NOT NULL DEFAULT 0,
  avg_execution_time DECIMAL(10,2) DEFAULT NULL,
  success_rate DECIMAL(5,2) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT uk_name_version UNIQUE (name, version),
  CONSTRAINT fk_solver_uploader FOREIGN KEY (uploaded_by)
    REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_is_active ON solver_versions (is_active);
CREATE INDEX idx_uploaded_by ON solver_versions (uploaded_by);
CREATE INDEX idx_success_rate ON solver_versions (success_rate);

-- ------------------------------------------------------------
-- 5. 求解文件表
-- ------------------------------------------------------------
CREATE TABLE solver_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  file_path VARCHAR(500) NOT NULL,
  description TEXT DEFAULT NULL,
  file_size BIGINT DEFAULT NULL,
  file_type VARCHAR(50) DEFAULT NULL,
  tags JSONB DEFAULT NULL,
  uploaded_by BIGINT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  usage_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT uk_file_path UNIQUE (file_path),
  CONSTRAINT fk_file_uploader FOREIGN KEY (uploaded_by)
    REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_name ON solver_files (name);
CREATE INDEX idx_file_type ON solver_files (file_type);
CREATE INDEX idx_uploaded_by ON solver_files (uploaded_by);
CREATE INDEX idx_is_active ON solver_files (is_active);

-- ------------------------------------------------------------
-- 6. 求解文件组表（支持多选文件）
-- ------------------------------------------------------------
CREATE TABLE solver_file_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  description TEXT DEFAULT NULL,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT fk_file_group_creator FOREIGN KEY (created_by)
    REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_created_by ON solver_file_groups (created_by);

-- 文件组与文件的关系表
CREATE TABLE solver_file_group_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL,
  file_id BIGINT NOT NULL,
  order_index INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_group_file UNIQUE (group_id, file_id),
  CONSTRAINT fk_group_item_group FOREIGN KEY (group_id)
    REFERENCES solver_file_groups (id) ON DELETE CASCADE,
  CONSTRAINT fk_group_item_file FOREIGN KEY (file_id)
    REFERENCES solver_files (id) ON DELETE CASCADE
);

CREATE INDEX idx_file_id ON solver_file_group_items (file_id);

-- ------------------------------------------------------------
-- 7. 计算任务主表
-- ------------------------------------------------------------
CREATE TABLE compute_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_name VARCHAR(200) NOT NULL,
  task_description TEXT DEFAULT NULL,
  solver_version_id BIGINT NOT NULL,
  solver_file_id BIGINT DEFAULT NULL,
  solver_file_group_id BIGINT DEFAULT NULL,
  server_id BIGINT DEFAULT NULL,
  gpu_id BIGINT DEFAULT NULL,
  gpu_index INTEGER DEFAULT NULL,
  parameters JSONB DEFAULT NULL,
  priority solver_priority NOT NULL DEFAULT 'NORMAL',
  status task_status NOT NULL DEFAULT 'PENDING',
  remote_pid VARCHAR(50) DEFAULT NULL,
  queue_position INTEGER DEFAULT NULL,
  estimated_duration INTEGER DEFAULT NULL,
  submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  queued_at TIMESTAMP DEFAULT NULL,
  started_at TIMESTAMP DEFAULT NULL,
  finished_at TIMESTAMP DEFAULT NULL,
  last_heartbeat TIMESTAMP DEFAULT NULL,
  timeout_at TIMESTAMP DEFAULT NULL,
  exit_code INTEGER DEFAULT NULL,
  error_message TEXT DEFAULT NULL,
  log_file_path VARCHAR(500) DEFAULT NULL,
  result_file_path VARCHAR(500) DEFAULT NULL,
  execution_time_seconds DECIMAL(10,2) DEFAULT NULL,
  peak_gpu_memory_mb INTEGER DEFAULT NULL,
  avg_gpu_utilization DECIMAL(5,2) DEFAULT NULL,
  submitted_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT fk_task_solver_version FOREIGN KEY (solver_version_id)
    REFERENCES solver_versions (id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_solver_file FOREIGN KEY (solver_file_id)
    REFERENCES solver_files (id) ON DELETE SET NULL,
  CONSTRAINT fk_task_file_group FOREIGN KEY (solver_file_group_id)
    REFERENCES solver_file_groups (id) ON DELETE SET NULL,
  CONSTRAINT fk_task_server FOREIGN KEY (server_id)
    REFERENCES compute_servers (id) ON DELETE SET NULL,
  CONSTRAINT fk_task_gpu FOREIGN KEY (gpu_id)
    REFERENCES gpu_resources (id) ON DELETE SET NULL,
  CONSTRAINT fk_task_submitter FOREIGN KEY (submitted_by)
    REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_solver_version ON compute_tasks (solver_version_id);
CREATE INDEX idx_solver_file ON compute_tasks (solver_file_id);
CREATE INDEX idx_file_group ON compute_tasks (solver_file_group_id);
CREATE INDEX idx_server ON compute_tasks (server_id);
CREATE INDEX idx_gpu ON compute_tasks (gpu_id);
CREATE INDEX idx_status ON compute_tasks (status);
CREATE INDEX idx_priority ON compute_tasks (priority);
CREATE INDEX idx_submitted_by ON compute_tasks (submitted_by);
CREATE INDEX idx_submitted_at ON compute_tasks (submitted_at);
CREATE INDEX idx_finished_at ON compute_tasks (finished_at);
CREATE INDEX idx_status_priority ON compute_tasks (status, priority);
CREATE INDEX idx_task_status_time ON compute_tasks (status, priority, submitted_at);
CREATE INDEX idx_task_gpu_status ON compute_tasks (gpu_id, status, queue_position);
CREATE INDEX idx_task_server_status ON compute_tasks (server_id, status, submitted_at);

-- ------------------------------------------------------------
-- 8. GPU任务队列表（用于手动调整顺序）
-- ------------------------------------------------------------
CREATE TABLE gpu_task_queues (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gpu_id BIGINT NOT NULL,
  task_id BIGINT NOT NULL,
  queue_position INTEGER NOT NULL,
  status queue_status NOT NULL DEFAULT 'QUEUED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT uk_gpu_position UNIQUE (gpu_id, queue_position),
  CONSTRAINT uk_task UNIQUE (task_id),
  CONSTRAINT fk_queue_gpu FOREIGN KEY (gpu_id)
    REFERENCES gpu_resources (id) ON DELETE CASCADE,
  CONSTRAINT fk_queue_task FOREIGN KEY (task_id)
    REFERENCES compute_tasks (id) ON DELETE CASCADE
);

CREATE INDEX idx_gpu_status ON gpu_task_queues (gpu_id, status);
CREATE INDEX idx_created_at ON gpu_task_queues (created_at);

-- ------------------------------------------------------------
-- 9. 任务执行日志表（详细记录）
-- ------------------------------------------------------------
CREATE TABLE task_execution_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL,
  log_level log_level NOT NULL DEFAULT 'INFO',
  log_message TEXT NOT NULL,
  log_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  source VARCHAR(100) DEFAULT NULL,
  metadata JSONB DEFAULT NULL,
  CONSTRAINT fk_log_task FOREIGN KEY (task_id)
    REFERENCES compute_tasks (id) ON DELETE CASCADE
);

CREATE INDEX idx_task_id ON task_execution_logs (task_id);
CREATE INDEX idx_log_level ON task_execution_logs (log_level);
CREATE INDEX idx_timestamp ON task_execution_logs (log_timestamp);
CREATE INDEX idx_task_timestamp ON task_execution_logs (task_id, log_timestamp);

-- ------------------------------------------------------------
-- 10. 性能比较结果表
-- ------------------------------------------------------------
CREATE TABLE solver_performance_comparisons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  base_solver_id BIGINT NOT NULL,
  compare_solver_id BIGINT NOT NULL,
  task_count INTEGER NOT NULL,
  avg_speedup DECIMAL(10,4) DEFAULT NULL,
  avg_execution_time_diff DECIMAL(10,2) DEFAULT NULL,
  success_rate_diff DECIMAL(5,2) DEFAULT NULL,
  result_accuracy DECIMAL(5,2) DEFAULT NULL,
  faster_count INTEGER DEFAULT 0,
  slower_count INTEGER DEFAULT 0,
  more_stable_count INTEGER DEFAULT 0,
  compared_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by BIGINT NOT NULL,
  CONSTRAINT uk_solver_pair UNIQUE (base_solver_id, compare_solver_id),
  CONSTRAINT fk_comparison_base_solver FOREIGN KEY (base_solver_id)
    REFERENCES solver_versions (id) ON DELETE CASCADE,
  CONSTRAINT fk_comparison_compare_solver FOREIGN KEY (compare_solver_id)
    REFERENCES solver_versions (id) ON DELETE CASCADE,
  CONSTRAINT fk_comparison_creator FOREIGN KEY (created_by)
    REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_compared_at ON solver_performance_comparisons (compared_at);
CREATE INDEX idx_created_by ON solver_performance_comparisons (created_by);

-- ------------------------------------------------------------
-- 11. 系统配置表
-- ------------------------------------------------------------
CREATE TABLE system_configurations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  config_key VARCHAR(100) NOT NULL,
  config_value TEXT DEFAULT NULL,
  config_type config_type NOT NULL DEFAULT 'STRING',
  description TEXT DEFAULT NULL,
  category VARCHAR(50) DEFAULT 'GENERAL',
  is_encrypted BOOLEAN NOT NULL DEFAULT FALSE,
  is_system BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  updated_by BIGINT DEFAULT NULL,
  CONSTRAINT uk_config_key UNIQUE (config_key),
  CONSTRAINT fk_config_updater FOREIGN KEY (updated_by)
    REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_category ON system_configurations (category);
CREATE INDEX idx_is_system ON system_configurations (is_system);

